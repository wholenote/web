/** Cuisine origins for map flags, separate from broad browsing categories. */
const countryCodes = {
  "United States": "us", China: "cn", Japan: "jp", "South Korea": "kr",
  Italy: "it", Mexico: "mx", Thailand: "th", Vietnam: "vn", India: "in",
  Taiwan: "tw", Turkey: "tr", Lebanon: "lb", Greece: "gr", Cuba: "cu",
  Pakistan: "pk", Nepal: "np", France: "fr", Iraq: "iq",
} as const;
export type CuisineCountry = keyof typeof countryCodes;

const categoryCountries: Record<Category, readonly CuisineCountry[]> = {
  American: ["United States"], BBQ: ["United States"], Breakfast: ["United States"],
  Burgers: ["United States"], Caribbean: ["Cuba"], Chinese: ["China"],
  Coffee: ["United States"], Dessert: ["United States"], Italian: ["Italy"],
  Japanese: ["Japan"], Korean: ["South Korea"],
  Mediterranean: ["Lebanon", "Greece", "Turkey"], Mexican: ["Mexico"], Pizza: ["Italy"],
  "South Asian": ["India"], Taiwanese: ["Taiwan"], Thai: ["Thailand"], Vietnamese: ["Vietnam"],
};

export const restaurantCuisineCountries = (item: Recommendation): readonly CuisineCountry[] =>
  item.cuisineCountries ?? categoryCountries[item.category];

export const restaurantFlagIcons = (item: Recommendation) =>
  restaurantCuisineCountries(item)
    .map(country => `<img class="category-flag" src="/flags/${countryCodes[country]}.svg" alt="" width="24" height="16" />`)
    .join("");

